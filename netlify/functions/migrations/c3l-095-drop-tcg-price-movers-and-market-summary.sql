-- c3l-095-drop-tcg-price-movers-and-market-summary.sql
-- Applied live 11 August 2026, task `task-deadtables-blogcontent`.
--
-- WHAT AND WHY
-- Drops `tcg_price_movers` and `tcg_market_summary`. Both were created as schema for a market
-- feature that was designed and never built. They are not "empty right now", which would prove
-- very little; they have NEVER held a row.
--
-- THE EVIDENCE THAT SETTLED IT, and note that the grep is the weakest part of it:
--
--   pg_stat_user_tables, read immediately before the drop:
--     tcg_price_movers    n_tup_ins 0, n_tup_upd 0, n_tup_del 0, seq_scan 6, 40 kB
--     tcg_market_summary  n_tup_ins 0, n_tup_upd 0, n_tup_del 0, seq_scan 5, 40 kB
--
--   n_tup_ins = 0 over the whole life of each table means no writer has ever existed, anywhere,
--   by any name. That is a stronger statement than "no file greps for the table", which is the
--   evidence C3L-95 was originally raised on and which its own row flagged as insufficient
--   ("a table addressed through a variable or built string would read as unreferenced when it
--   is not"). The 6 and 5 sequential scans are this programme's own audit queries, the most
--   recent on 2026-08-08.
--
--   Code, whole repo and every branch, not just netlify/functions/: the only reference on
--   main, blog-content, c3-gsc-collapse-detector and c3-legacy-html-rewrites is a COMMENT in
--   generate-weekly-digest-free.mjs, and that comment exists to say the digest does NOT read
--   these tables. Plus the register itself. Zero executable references.
--
--   Database dependents, checked explicitly rather than assumed: no views or rules
--   (pg_depend/pg_rewrite), no function body mentioning either name (pg_proc.prosrc), no
--   foreign keys in either direction, no pg_cron job, no non-internal trigger. The only
--   dependent objects are the four RLS policies below, which drop with their tables.
--
-- A SIDE BENEFIT WORTH NAMING, because it is the actual argument for doing this at all. The
-- cost was never the 80 kB. C3L-95 recorded that dead schema DILUTES the recurring RLS check:
-- that check sweeps tables by column shape, and its own logs note that an empty table proves
-- nothing. Removing tables that can never hold a row makes the next green RLS pass mean more
-- than the last one did.
--
-- ROLLBACK. Everything needed to put both tables back exactly as they were is at the bottom of
-- this file, reconstructed from information_schema.columns, pg_indexes, pg_constraint and
-- pg_policy on the day of the drop. There is no data to restore, because there never was any.

